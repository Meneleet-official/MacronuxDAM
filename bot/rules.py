_SEV_SHIFT = {"low": -1, "high": 1}


def tier_durations(rule_id: str, violations: int, severity: str = "medium",
                   server_tiers=None):
    """Длительности для кнопок: решает, какое наказание положено по правилу
    при текущем числе нарушений и severity детекта. Возвращает (timeout_сек|None,
    ban_сек|None, primary_action, primary_сек)."""
    tiers = server_tiers or RULE_TIERS.get(rule_id, DEFAULT_TIERS)
    n = max(1, violations) + _SEV_SHIFT.get(severity, 0)
    n = max(1, min(n, len(tiers)))

    def resolve(action):
        best = None
        for min_n, a, secs in tiers:
            if a == action and min_n <= n:
                best = secs
        if best is not None:
            return best
        for min_n, a, secs in tiers:
            if a == action:
                return secs
        return None

    primary_action, primary_secs = "timeout", DEFAULT_TIERS[-1][2]
    for min_n, a, secs in tiers:
        if n >= min_n:
            primary_action, primary_secs = a, secs
    return resolve("timeout"), resolve("ban"), primary_action, primary_secs


def suggest_punishment(rule_id: str, violations: int,
                       severity: str = "medium"):
    """Краткая рекомендация для панели: (действие, срок_сек или None)."""
    _, _, primary_action, primary_secs = tier_durations(rule_id, violations, severity)
    return primary_action, primary_secs


def build_suggest(rule_id: str, violations: int, severity: str = "medium",
                  server_tiers=None) -> dict:
    """Рекомендация для кнопок: {"timeout": сек|None, "ban": сек|None,
    "action": str, "primary_secs": сек_рекомендуемого_действия|None}."""
    t, b, act, prim = tier_durations(rule_id, violations, severity, server_tiers)
    return {"timeout": t, "ban": b, "action": act, "primary_secs": prim}


def fmt_duration(seconds) -> str:
    """человекочитаемый срок: '30м', '3ч', '7д', '14д', 'перманентный'."""
    if seconds is None:
        return "перманентно"
    if seconds <= 0:
        return "0"
    if seconds < 60:
        return "1м"
    if seconds < 3600:
        return f"{seconds // 60}м"
    if seconds < 86400:
        h = round(seconds / 3600) or 1
        return f"{h}ч"
    days = round(seconds / 86400)
    return f"{days}д"


