def _variants(word: str):
    """Generate obfuscated variants of a word for regex matching."""
    variants = {word}
    # @ and 0 replaced patterns for a/e/o/i letters
    mapping = {
        "а": ["а", "a", "@"],
        "е": ["е", "e", "ё"],
        "о": ["о", "o", "0"],
        "и": ["и", "i", "1"],
        "с": ["с", "c"],
        "з": ["з", "3"],
        "б": ["б", "6"],
        "х": ["х", "x"],
    }
    from itertools import product
    # Build all combinations of letter substitutions for obfuscation detection
    chars = list(word)
    pools = []
    for ch in chars:
        pools.append(mapping.get(ch.lower(), [ch.lower()]))
    for combo in product(*pools):
        variants.add("".join(combo))
    return variants


